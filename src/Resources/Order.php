<?php

namespace Codebrainbv\Smartpay\Resources;

use Codebrainbv\Smartpay\Resources\BaseResource;
use Codebrainbv\Smartpay\States\PaymentStates;

class Order extends BaseResource
{
    /**
     * Amount to be paid in decimal format (e.g., 10.00 for €10.00).
     * The SDK automatically converts this to cents and wraps it with currency info.
     *
     * You can pass either:
     * - A float/string: 10.00 (currency defaults to EUR)
     * - An array: ['amount' => 1000, 'currency' => 'EUR'] (already in cents, if you need a custom currency)
     *
     * The SDK will send to the API as: {'amount': 1000, 'currency': 'EUR'}
     *
     * @var string|float|array
     */
    public $amount;

    /**
     * Customer details that are typically of interest for cards transactions
     *
     * The array should contain keys such as:
     *
     * - dateOfBirth
     * - fullName
     * - emailAddress
     * - gender
     * - initials
     * - telephoneNumber
     *
     * Each key should have a corresponding value representing the respective customer detail.
     *
     * @var array (optional)
     */
    public array $customerInformation;

    /**
     * Description of the order. (max 35 characters)
     * If it contains more than 35 characters then then Rabo Smart pay will remove the characters.
     *
     * @var string (optional)
     */
    public ?string $description;

    /**
     * This field is used to track transactions initiated by a specific party.
     * Only supply this field in consultation with the Rabobank.
     *
     * @var string (optional)
     */
    public ?string $initiatingParty;

    /**
     * The language of the payment pages.
     * Supported languages are:
     *
     * - NL
     * - EN
     * - DE
     * - FR
     *
     * @var string (optional)
     */
    public ?string $language;

    /**
     * Generated by the webshop.
     * This field has two types of validations based on if
     * the shopperBankstatementReference is supplied or not.
     *
     * If shopperBankstatementReference is supplied:
     *
     * It allows all ascii characters up to a length of 64 characters,
     * if the ID contains more than 64 characters,
     * the extra characters are removed after the 64th character.
     *
     * Else:
     *
     * It should adhere to the pattern: '[A-Za-z0-9]{1,24}',
     * if the ID contains more than 24 characters,
     * the extra characters are removed after the 24th character.
     * @var string
     */
    public string $merchantOrderId;

    /**
     * The URL to which the shopper will be redirected after completing the payment.
     * @var string
     */
    public string $merchantReturnUrl;

    /**
     * This field is optional and is used to enforce a specific payment method with
     * the consumer instead of the consumer selecting a payment method
     * on the payment method selection page.
     *
     * Possible values are:
     *
     * - IDEAL
     * - PAYPAL
     * - MASTERCARD
     * - VISA
     * - BANCONTACT
     * - MAESTRO
     * - V_PAY
     * - CARDS
     *
     * The CARDS value ensures that the consumer can choose between payment methods:
     *
     * MASTERCARD, VISA, BANCONTACT, MAESTRO and V_PAY.
     *
     * @var string (optional)
     */
    public ?string $paymentBrand;

    /**
     * This field should only be delivered if the paymentBrand field (see above)
     * is also specified. In the case of FORCE_ONCE,
     * the indicated paymentBrand is only enforced on the first attempt.
     * If this fails, the consumer can still choose another payment method.
     * When FORCE_ALWAYS is chosen, the consumer is not allowed choose another payment method.
     * Possible values are:
     *
     * - FORCE_ONCE
     * - FORCE_ALWAYS
     *
     * @var string (optional)
     */
    public ?string $paymentBrandForce;

    /**
     * Generated by the webshop.
     * If the ID contains more than 24 characters, the extra characters are removed after the 24th character.
     *
     * Value should be alfanumeric:
     *
     * - Pattern: '[A-Za-z0-9]{1,24}'
     *
     * @var string (optional)
     */
    public ?string $shopperBankstatementReference;

    /**
     * This field is used by the Smart Pay API to determine whether
     * the consumer should be redirected to the HPP result page or not.
     * By default this field is set to false.
     *
     * Possible values are:
     * - true
     * - false
     * @var bool (optional)
     */
    public ?bool $skipHppResultPage;

    /**
     * Timestamp of the order announcement.
     * As a rule this is the current date and time (ISO 8601 format).
     *
     * Example: '2016-11-24T16:54:51.216+0000'
     * @var string
     */
    public string $timestamp;

    /**
     * The URL to which the consumer should be redirected to complete the payment.
     * @var string
     */
    public string $redirectUrl;

    /**
     * The Omnikassa Order ID for this order at Rabo Smart Pay.
     * @var string
     */
    public string $omnikassaOrderId;

    /**
     * Allowed properties for this resource.
     *
     * @var array
     */
    protected static $allowedProperties = [
        'amount',
        'customerInformation',
        'description',
        'initiatingParty',
        'language',
        'merchantOrderId',
        'merchantReturnUrl',
        'paymentBrand',
        'paymentBrandForce',
        'shopperBankstatementReference',
        'skipHppResultPage',
        'timestamp',
        'redirectUrl',
        'omnikassaOrderId'
    ];

    /**
     * Get the Omnikassa Order ID.
     *
     * @return string|null
     */
    public function getOmnikassaOrderId()
    {
        if (empty($this->omnikassaOrderId)) {
            return null;
        }

        return $this->omnikassaOrderId;
    }

    /**
     * Get the redirect URL where the customer can complete the payment.
     *
     * @return string|null
     */
    public function getRedirectUrl()
    {
        if (empty($this->redirectUrl)) {
            return null;
        }

        return $this->redirectUrl;
    }
}
